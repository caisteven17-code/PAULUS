  scheme_id, position, minimum_amount, maximum_amount, rate
)
SELECT scheme.id, bracket.position, bracket.minimum_amount, bracket.maximum_amount, bracket.rate
FROM diocese.progressive_tax_schemes scheme
CROSS JOIN (
  VALUES
    (1::smallint,       1.00::numeric,   25000.00::numeric, 0.125::numeric),
    (2::smallint,   25000.01::numeric,   50000.00::numeric, 0.150::numeric),
    (3::smallint,   50000.01::numeric,   80000.00::numeric, 0.175::numeric),
    (4::smallint,   80000.01::numeric,  100000.00::numeric, 0.200::numeric),
    (5::smallint,  100000.01::numeric,  120000.00::numeric, 0.215::numeric),
    (6::smallint,  120000.01::numeric,  125000.00::numeric, 0.225::numeric),
    (7::smallint,  125000.01::numeric,  150000.00::numeric, 0.240::numeric),
    (8::smallint,  150000.01::numeric, 1000000.00::numeric, 0.250::numeric)
) AS bracket(position, minimum_amount, maximum_amount, rate)
WHERE scheme.effective_month = DATE '2026-01-01'
  AND scheme.name = 'Progressive Taxation Scheme 2026'
  AND scheme.status = 'draft'
ON CONFLICT (scheme_id, position) DO NOTHING;

